/**
 * PR changeset check.
 *
 * Policy: feature PRs carry a PENDING changeset and do NOT bump the version.
 * Versioning happens only on merge to main — the Changesets GitHub Action
 * (`.github/workflows/changesets.yml`) consumes pending changesets and opens a
 * "Version Packages" PR that bumps `package.json`, `CHANGELOG.md`, and
 * `research/version.tex`.
 *
 * So on a normal PR we require:
 *   - a pending `.changeset/*.md` when shipped source (`src/`/`bin/`/`packages/kb-server/`) changed,
 *   - the package.json `version` is unchanged from base, and
 *   - `CHANGELOG.md` / `research/version.tex` are not hand-edited.
 *
 * (Other package.json edits — dependencies, scripts — are fine.)
 *
 * Usage:
 *   node scripts/check-changeset-consistency.mjs --base origin/main
 */
import { execSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

function parseArgs(argv) {
  let base = 'origin/main'
  for (let i = 2; i < argv.length; i++) {
    if (argv[i] === '--base' && argv[i + 1]) {
      base = argv[++i]
      continue
    }
    throw new Error(`Unknown argument: ${argv[i]}`)
  }
  return { base }
}

function git(args) {
  return execSync(`git ${args}`, { cwd: root, encoding: 'utf-8' }).trim()
}

function listPendingChangesets() {
  const dir = path.join(root, '.changeset')
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter(name => name.endsWith('.md') && name !== 'README.md')
    .map(name => `.changeset/${name}`)
}

function readPackageVersion(ref) {
  return JSON.parse(git(`show ${ref}:package.json`)).version
}

function readHeadPackageVersion() {
  return JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf-8')).version
}

export function evaluateChangesetConsistency(input) {
  const errors = []
  const notes = []

  const changed = new Set(input.changedFiles)
  const sourceChanged = [...changed].some(
    file =>
      file.startsWith('src/') ||
      file.startsWith('bin/') ||
      file.startsWith('packages/kb-server/')
  )
  const pending = input.pendingChangesets
  const versionBumped = input.basePackageVersion !== input.headPackageVersion

  // The version + changelog are produced only by the "Version Packages" PR on
  // merge to main — never hand-edited in a feature PR.
  if (versionBumped) {
    errors.push(
      `Do not bump the package.json version in a feature PR (${input.basePackageVersion} → ${input.headPackageVersion}). Versioning happens on merge to main via the Changesets action; add a changeset with \`pnpm run changeset\` instead.`
    )
  }
  if (changed.has('CHANGELOG.md')) {
    errors.push(
      'Do not edit CHANGELOG.md in a feature PR — it is generated by the "Version Packages" PR on merge to main. Add a changeset instead.'
    )
  }
  if (changed.has('research/version.tex')) {
    errors.push(
      'Do not edit research/version.tex in a feature PR — it is regenerated on merge to main.'
    )
  }

  // Shipped source needs a pending changeset so the release PR can bump + changelog.
  if (sourceChanged) {
    if (pending.length === 0) {
      errors.push(
        'Shipped source (src/, bin/, or packages/kb-server/) changed without a changeset. Run `pnpm run changeset` to add one — it stays pending until merge to main.'
      )
    } else {
      notes.push(`Pending changeset(s): ${pending.join(', ')}`)
    }
  } else {
    notes.push('No shipped source changes — changeset not required.')
  }

  return { ok: errors.length === 0, errors, notes }
}

function main() {
  const { base } = parseArgs(process.argv)
  git(`fetch --no-tags origin ${base.replace(/^origin\//, '')}`)
  const changedFiles = git(`diff --name-only ${base}...HEAD`)
    .split('\n')
    .map(line => line.trim())
    .filter(Boolean)

  const result = evaluateChangesetConsistency({
    changedFiles,
    pendingChangesets: listPendingChangesets(),
    basePackageVersion: readPackageVersion(base),
    headPackageVersion: readHeadPackageVersion(),
  })

  for (const note of result.notes) {
    console.log(`✓ ${note}`)
  }

  if (!result.ok) {
    for (const error of result.errors) {
      console.error(`❌ ${error}`)
    }
    process.exit(1)
  }

  console.log('✓ Changeset state is consistent.')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main()
}
