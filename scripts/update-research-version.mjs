/**
 * Syncs research/version.tex with the current package.json version and today's date.
 * Called automatically by `pnpm run version` after `changeset version` bumps package.json.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const root = new URL('..', import.meta.url).pathname
const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf-8'))
const version = pkg.version

const now = new Date()
const releaseDate = now.toLocaleDateString('en-US', {
  year: 'numeric',
  month: 'long',
  day: 'numeric',
})

const content = `% Auto-generated by scripts/update-research-version.mjs — do not edit by hand.
\\def\\kbversion{${version}}
\\def\\kbreleasedate{${releaseDate}}
`

const outPath = path.join(root, 'research', 'version.tex')
writeFileSync(outPath, content, 'utf-8')
console.log(`→ research/version.tex updated to v${version} (${releaseDate})`)
